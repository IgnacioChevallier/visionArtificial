from torch.utils.data import Dataset, DataLoader
import torchvision.transforms as T

MEAN = [0.485, 0.456, 0.406]
STD  = [0.229, 0.224, 0.225]

class BrainMRIDataset(Dataset):
    def __init__(self, indices, img_paths, mask_paths, augment=False):
        self.indices    = indices
        self.img_paths  = img_paths
        self.mask_paths = mask_paths
        self.augment    = augment
        self.normalize  = T.Normalize(mean=MEAN, std=STD)

    def __len__(self):
        return len(self.indices)

    def _augment(self, img, mask):
        # Flip horizontal
        if random.random() > 0.5:
            img  = TF.hflip(img)
            mask = TF.hflip(mask)
        # Flip vertical
        if random.random() > 0.5:
            img  = TF.vflip(img)
            mask = TF.vflip(mask)
        # Rotación aleatoria ±30°
        angle = random.uniform(-30, 30)
        img   = TF.rotate(img, angle)
        mask  = TF.rotate(mask, angle)
        # Brillo y contraste
        img = TF.adjust_brightness(img, random.uniform(0.8, 1.2))
        img = TF.adjust_contrast(img,   random.uniform(0.8, 1.2))
        return img, mask

    def __getitem__(self, item):
        idx  = self.indices[item]
        img  = Image.open(self.img_paths[idx]).convert('RGB').resize(
                   (IMG_SIZE, IMG_SIZE), Image.BILINEAR)
        mask = Image.open(self.mask_paths[idx]).convert('L').resize(
                   (IMG_SIZE, IMG_SIZE), Image.NEAREST)

        img  = TF.to_tensor(img)           # [3, H, W], float [0,1]
        mask = TF.to_tensor(mask)          # [1, H, W], float [0,1]
        mask = (mask > 0.5).float()

        if self.augment:
            img_pil  = TF.to_pil_image(img)
            mask_pil = TF.to_pil_image(mask)
            img_pil, mask_pil = self._augment(img_pil, mask_pil)
            img  = TF.to_tensor(img_pil)
            mask = TF.to_tensor(mask_pil)
            mask = (mask > 0.5).float()

        img = self.normalize(img)
        return img, mask


