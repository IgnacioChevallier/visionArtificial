"""## 5. Arquitectura U-Net

Implementación desde cero de la U-Net con las siguientes adaptaciones:
- **Padding** `same` para que las resoluciones coincidan sin necesidad de cropping. Basicamente se agregan píxeles de relleno (ceros) alrededor para que la salida tenga el mismo tamaño que la entrada.
- Batch **Normalization** después de cada convolución, lo que estabiliza el entrenamiento.
Input  →  Convolución  →  Batch Norm  →  ReLU  →  Output
- **Dropout** en el cuello de botella que es donde existe mayor riesgo de que el modelo memorice el dataset de entrenamiento. El Dropout fuerza a la red a no depender de ninguna neurona específica, mejorando la generalización.

```
Encoder (contracción):  3 → 64 → 128 → 256 → 512
Bottleneck:             512 → 1024
Decoder (expansión):    1024 → 512 → 256 → 128 → 64
Output:                 64 → 1  (sigmoid)
```
"""

import torch.nn as nn
import torch.nn.functional as F


class ConvBlock(nn.Module):
    """Dos convoluciones 3×3 con BN y ReLU."""
    def __init__(self, in_ch, out_ch, dropout=0.0):
        super().__init__()
        self.block = nn.Sequential(
            nn.Conv2d(in_ch, out_ch, 3, padding=1, bias=False),
            nn.BatchNorm2d(out_ch),
            nn.ReLU(inplace=True),
            nn.Conv2d(out_ch, out_ch, 3, padding=1, bias=False),
            nn.BatchNorm2d(out_ch),
            nn.ReLU(inplace=True),
            nn.Dropout2d(dropout),
        )

    def forward(self, x):
        return self.block(x)


class UNet(nn.Module):
    def __init__(self, in_channels=3, out_channels=1, features=[64, 128, 256, 512]):
        super().__init__()
        self.encoder = nn.ModuleList()
        self.decoder = nn.ModuleList()
        self.pool    = nn.MaxPool2d(2, 2)

        # Encoder
        ch = in_channels
        for f in features:
            self.encoder.append(ConvBlock(ch, f))
            ch = f

        # Bottleneck
        self.bottleneck = ConvBlock(features[-1], features[-1] * 2, dropout=0.3)

        # Decoder
        for f in reversed(features):
            self.decoder.append(
                nn.ConvTranspose2d(f * 2, f, kernel_size=2, stride=2)
            )
            self.decoder.append(ConvBlock(f * 2, f))

        self.final_conv = nn.Conv2d(features[0], out_channels, kernel_size=1)

    def forward(self, x):
        skip_connections = []

        # Encoder
        for enc in self.encoder:
            x = enc(x)
            skip_connections.append(x)
            x = self.pool(x)

        x = self.bottleneck(x)
        skip_connections = skip_connections[::-1]  # invertir

        # Decoder
        for i in range(0, len(self.decoder), 2):
            x    = self.decoder[i](x)                 # upsampling
            skip = skip_connections[i // 2]
            # Por si las dimensiones no coinciden exactamente
            if x.shape != skip.shape:
                x = F.interpolate(x, size=skip.shape[2:], mode='bilinear', align_corners=False)
            x = torch.cat([skip, x], dim=1)
            x = self.decoder[i + 1](x)               # conv block

        return self.final_conv(x)  # sin activación (BCEWithLogitsLoss)


