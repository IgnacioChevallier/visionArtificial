"""## 6. Entrenamiento

**Función de pérdida:** combinación de BCE + Dice Loss.  
La Dice Loss es especialmente útil en datasets con fuerte desbalance de clases (la mayoría de los píxeles son fondo).
- El **Dice score** e **IoU** (Intersection over Union) miden la superposición entre la máscara de tumor predicha y la real. La diferencia es que IoU penaliza más que Dice Score.

Al tratar con tumores, Dice Score suele ser la métrica preferida, porque es más estable cuando la región es chica.

$$\mathcal{L} = \text{BCE} + (1 - \text{Dice})$$
"""

device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
print(f'Dispositivo: {device}')


def dice_loss(pred_logits, target, smooth=1.0):
    pred = torch.sigmoid(pred_logits)
    pred   = pred.view(-1)
    target = target.view(-1)
    intersection = (pred * target).sum()
    return 1 - (2 * intersection + smooth) / (pred.sum() + target.sum() + smooth)


def combined_loss(pred_logits, target):
    bce  = F.binary_cross_entropy_with_logits(pred_logits, target)
    dice = dice_loss(pred_logits, target)
    return bce + dice


def dice_score(pred_logits, target, threshold=0.5, smooth=1.0):
    """Dice coefficient como métrica (no como loss)."""
    pred = (torch.sigmoid(pred_logits) > threshold).float()
    pred   = pred.view(-1)
    target = target.view(-1)
    intersection = (pred * target).sum()
    return ((2 * intersection + smooth) / (pred.sum() + target.sum() + smooth)).item()


def iou_score(pred_logits, target, threshold=0.5, smooth=1.0):
    pred = (torch.sigmoid(pred_logits) > threshold).float()
    pred   = pred.view(-1)
    target = target.view(-1)
    intersection = (pred * target).sum()
    union = pred.sum() + target.sum() - intersection
    return ((intersection + smooth) / (union + smooth)).item()

