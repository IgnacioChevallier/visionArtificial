# Verde = verdadero positivo, Rojo = falso positivo, Azul = falso negativo
def show_overlap(dataset, n=4):
    indices = random.sample(range(len(dataset)), n)
    fig, axes = plt.subplots(1, n, figsize=(4 * n, 4))

    for col, i in enumerate(indices):
        img_t, mask_t = dataset[i]
        with torch.no_grad():
            pred = (torch.sigmoid(model(img_t.unsqueeze(0).to(device))).squeeze().cpu() > 0.5).numpy()
        gt   = mask_t.squeeze().numpy().astype(bool)
        pred = pred.astype(bool)

        img_vis = denorm(img_t).permute(1, 2, 0).numpy().copy()
        img_vis[gt  & pred]  = [0, 1, 0]   # TP — verde
        img_vis[~gt & pred]  = [1, 0, 0]   # FP — rojo
        img_vis[gt  & ~pred] = [0, 0, 1]   # FN — azul

        axes[col].imshow(img_vis)
        axes[col].set_title('Verde=TP  Rojo=FP  Azul=FN')
        axes[col].axis('off')

    plt.suptitle('Análisis de errores del modelo', fontsize=13)
    plt.tight_layout()
    plt.show()

